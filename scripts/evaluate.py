"""Produce honest, reproducible metrics you can quote on a resume.

  python scripts/evaluate.py                       # offline run on the fictional sample feeds
  python scripts/evaluate.py --live                # live RSS feeds (needs network; numbers vary daily)
  python scripts/evaluate.py --labels data/eval/headlines_labelled.csv
  python scripts/evaluate.py --write               # also write docs/EVAL.md

Only quote numbers you generated yourself, and say what they were measured on.
"""
import argparse
import csv
import json
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from app.analytics.sentiment import analyze  # noqa: E402


def sentiment_accuracy(path: Path) -> dict:
    rows = list(csv.DictReader(path.open(encoding="utf-8")))
    labels = ["positive", "neutral", "negative"]
    conf = {a: {b: 0 for b in labels} for a in labels}
    for r in rows:
        conf[r["label"].strip()][analyze(r["headline"])[1]] += 1
    correct = sum(conf[x][x] for x in labels)
    return {"n": len(rows), "accuracy": round(correct / len(rows), 3), "confusion": conf}


def pipeline_metrics(live: bool) -> dict:
    from app.agents.llm import build_llm_client
    from app.config import Settings, get_settings
    from app.ingestion.rss_reader import FeedFetcher
    from app.schemas.briefing import GenerateRequest
    from app.storage.repository import SQLiteRepository
    from app.workflows.briefing_workflow import BriefingWorkflow

    repo = SQLiteRepository(str(Path(tempfile.mkdtemp()) / "eval.db"))
    repo.init()
    topics = ["ai", "technology", "markets", "business", "energy", "economy"]
    if live:
        settings = get_settings()
        wf = BriefingWorkflow(settings, repo, FeedFetcher(settings), build_llm_client(settings))
        req, now, scope = GenerateRequest(topics=topics, days=2, use_llm=settings.llm_configured), None, "live feeds"
    else:
        import generate_sample as gs

        feeds = {name: f"https://feeds.sample.invalid/{i}" for i, name in enumerate(gs.SAMPLE)}
        routes = {feeds[n]: gs.rss(items) for n, items in gs.SAMPLE.items()}
        settings = Settings(allow_private_hosts=True, feeds=feeds, http_retries=0, cache_ttl_s=0)
        wf = BriefingWorkflow(settings, repo, FeedFetcher(settings, gs._Session(routes)), None)
        req, now, scope = GenerateRequest(topics=topics, days=3), gs.NOW, "fictional sample feeds (offline)"
    t0 = time.perf_counter()
    b = wf.run(req, now=now)
    elapsed = round(time.perf_counter() - t0, 2)
    status = repo.latest_status()
    stage = {s.name: s.detail for s in status.stages}
    checks = b.validation.checks
    n = max(1, len(checks))
    return {
        "scope": scope, "mode": b.mode, "seconds": elapsed,
        "stages": stage, "feed_errors": len([e for e in status.errors]),
        "claims_in_briefing": len(b.key_developments),
        "claims_corroborated_multi_publisher": sum(c.kind == "verified_fact" for c in b.key_developments),
        "claims_supported_pct": round(100 * sum(c.status == "supported" for c in checks) / n, 1),
        "unsupported_claims_removed": b.validation.unsupported_removed,
        "validation_passed": b.validation.passed,
        "measured_at": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--live", action="store_true")
    ap.add_argument("--labels", default=str(ROOT / "data/eval/headlines_labelled.csv"))
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    result = {"pipeline": pipeline_metrics(a.live)}
    if Path(a.labels).exists():
        result["sentiment_baseline"] = sentiment_accuracy(Path(a.labels))
    print(json.dumps(result, indent=2))
    if a.write:
        p, s = result["pipeline"], result.get("sentiment_baseline")
        lines = ["# Evaluation (generated by scripts/evaluate.py)", "",
                 f"Pipeline measured on: **{p['scope']}** on {p['measured_at']}; mode `{p['mode']}`; {p['seconds']} s.", "",
                 "| Metric | Value |", "|---|---|"]
        lines += [f"| {k} | {p[k]} |" for k in ("claims_in_briefing", "claims_corroborated_multi_publisher",
                                                   "claims_supported_pct", "unsupported_claims_removed", "validation_passed")]
        if s:
            lines += ["", f"Rule-based sentiment baseline on `{Path(a.labels).name}`: **{s['accuracy']:.1%}** accuracy "
                      f"over n={s['n']} labelled headlines. This file is author-written and illustrative; "
                      "replace it with real, independently labelled headlines before quoting the number."]
        (ROOT / "docs/EVAL.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
